/* Builds the vendored third-party bundles. Run: npm run build:vendor
 *  1. src/Vendor_P256.gs  - ECDSA P-256 *verification* for Apps Script (server side).
 *     Source: @noble/curves (MIT, Paul Miller) + @noble/hashes (MIT). Only verify() is used.
 *  1b. src/Vendor_AES.gs  - AES-256-GCM (@noble/ciphers) for encrypting phone numbers at rest (A2).
 *  2. src/Vendor_QR.html  - qrcode-generator (MIT, Kazuhiko Arase) for the student QR (client side).
 * Neither is hand-edited; regenerate instead. Licences are carried in the file banners.
 */
const esbuild = require('esbuild');
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');

function ver(p) { return JSON.parse(fs.readFileSync(path.join(root, 'node_modules', p, 'package.json'), 'utf8')).version; }

(async () => {
  // ---- 1. P-256 verifier for Apps Script V8 -------------------------------------------------
  const entry = `import { p256 } from '@noble/curves/p256';
  // Expose a deliberately tiny surface: verify only. Hashing is done with Utilities.computeDigest (native).
  globalThis.NobleP256 = {
    verify: function (sigBytes, digestBytes, pubKeyBytes) {
      return p256.verify(sigBytes, digestBytes, pubKeyBytes, { lowS: false });
    }
  };`;
  const r1 = await esbuild.build({
    stdin: { contents: entry, resolveDir: root, loader: 'js' },
    bundle: true, minify: true, format: 'iife', target: 'es2020', write: false, legalComments: 'none',
  });
  const banner = `/**
 * Vendor_P256.gs  --  GENERATED by scripts/build-vendor.js. DO NOT EDIT.
 * Contains @noble/curves ${ver('@noble/curves')} and @noble/hashes ${ver('@noble/hashes')} (both MIT licence,
 * Copyright (c) 2022 Paul Miller, https://paulmillr.com). Used ONLY for ECDSA P-256 signature verification
 * because Apps Script has no built-in asymmetric-signature verification.
 * MIT licence text: https://github.com/paulmillr/noble-curves/blob/main/LICENSE
 */
`;
  fs.writeFileSync(path.join(root, 'src', 'Vendor_P256.gs'), banner + r1.outputFiles[0].text);

  // ---- 1b. AES-256-GCM for Apps Script V8 (A2: phone numbers at rest) -----------------------
  // Apps Script has no symmetric cipher, so a vetted, audited implementation is bundled instead of a homemade one.
  const aesEntry = `import { gcm } from '@noble/ciphers/aes';
  // Authenticated encryption only: seal returns ciphertext || 16-byte tag; open throws when the tag does not verify.
  globalThis.NobleAES = {
    seal: function (key, nonce, plain, aad) { return gcm(key, nonce, aad).encrypt(plain); },
    open: function (key, nonce, sealed, aad) { return gcm(key, nonce, aad).decrypt(sealed); }
  };`;
  const r1b = await esbuild.build({
    stdin: { contents: aesEntry, resolveDir: root, loader: 'js' },
    bundle: true, minify: true, format: 'iife', target: 'es2020', write: false, legalComments: 'none',
  });
  const aesBanner = `/**
 * Vendor_AES.gs  --  GENERATED by scripts/build-vendor.js. DO NOT EDIT.
 * Contains @noble/ciphers ${ver('@noble/ciphers')} (MIT licence, Copyright (c) 2022 Paul Miller, https://paulmillr.com).
 * Used ONLY for AES-256-GCM authenticated encryption of personal data at rest (Crypt in Util.gs), because Apps Script
 * has no built-in symmetric cipher. MIT licence text: https://github.com/paulmillr/noble-ciphers/blob/main/LICENSE
 */
`;
  fs.writeFileSync(path.join(root, 'src', 'Vendor_AES.gs'), aesBanner + r1b.outputFiles[0].text);

  // ---- 2. QR generator for the browser ------------------------------------------------------
  const qrSrc = fs.readFileSync(path.join(root, 'node_modules/qrcode-generator/dist/qrcode.js'), 'utf8');
  const r2 = await esbuild.transform(qrSrc, { minify: true, target: 'es2018', legalComments: 'none' });
  const code = r2.code.replace(/<\/script/gi, '<\\/script');
  const html = `<!-- Vendor_QR.html -- GENERATED by scripts/build-vendor.js. DO NOT EDIT.
     qrcode-generator ${ver('qrcode-generator')}, MIT licence, Copyright (c) 2009 Kazuhiko Arase. https://github.com/kazuhikoarase/qrcode-generator -->
<script>
${code}
</script>
`;
  fs.writeFileSync(path.join(root, 'src', 'Vendor_QR.html'), html);
  console.log('Vendor_P256.gs', fs.statSync(path.join(root, 'src/Vendor_P256.gs')).size, 'bytes;',
              'Vendor_QR.html', fs.statSync(path.join(root, 'src/Vendor_QR.html')).size, 'bytes');
})().catch((e) => { console.error(e); process.exit(1); });
